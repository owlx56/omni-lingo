import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { UI_LANGS, type UiLang } from "../src/lib/languages";
import {
  EN_MESSAGES,
  I18N_CATALOG,
  type MessageKey,
} from "../src/lib/i18n/catalog";

const ROOT_DIR = dirname(dirname(fileURLToPath(import.meta.url)));
const LOCALES_DIR = join(ROOT_DIR, "src", "lib", "i18n", "locales");
const PDF_VIEWER_LOCALE_FILE = join(
  ROOT_DIR,
  "src",
  "assets",
  "pdf-viewer",
  "locales.generated.mjs",
);

const PDF_VIEWER_PREFIX = "pdfViewer.";
const PDFJS_PREFIX = "pdfViewer.pdfjs.";

const PDFJS_MESSAGE_KEYS = {
  freeTextDefaultContent: "pdfViewer.pdfjs.freeTextDefaultContent",
  highlightEditor: "pdfViewer.pdfjs.highlightEditor",
  inkEditor: "pdfViewer.pdfjs.inkEditor",
  pageLandmark: "pdfViewer.pdfjs.pageLandmark",
  stampEditor: "pdfViewer.pdfjs.stampEditor",
  textEditor: "pdfViewer.pdfjs.textEditor",
} as const satisfies Record<string, MessageKey>;

type RuntimeDict = Record<string, string>;

async function main(): Promise<void> {
  await mkdir(LOCALES_DIR, { recursive: true });
  await mkdir(dirname(PDF_VIEWER_LOCALE_FILE), { recursive: true });

  await Promise.all([
    writeLocaleWrappers(),
    writePdfViewerLocales(),
  ]);
}

async function writeLocaleWrappers(): Promise<void> {
  const files = UI_LANGS.map((lang) =>
    writeFile(join(LOCALES_DIR, `${lang}.ts`), localeWrapper(lang), "utf8"),
  );
  files.push(
    writeFile(
      join(LOCALES_DIR, "index.ts"),
      [
        "// Generated by scripts/generate-i18n.ts. Do not edit directly.",
        'import { I18N_CATALOG } from "../catalog";',
        "",
        "export const MESSAGES = I18N_CATALOG;",
        "",
      ].join("\n"),
      "utf8",
    ),
  );
  await Promise.all(files);
}

function localeWrapper(lang: UiLang): string {
  const typeName = lang === "en" ? "Dict" : "PartialDict";
  const constName = localeConstName(lang);
  return [
    "// Generated by scripts/generate-i18n.ts. Do not edit directly.",
    'import { I18N_CATALOG } from "../catalog";',
    `import type { ${typeName} } from "../messages";`,
    "",
    `const ${constName}: ${typeName} = I18N_CATALOG[${JSON.stringify(lang)}];`,
    "",
    `export default ${constName};`,
    "",
  ].join("\n");
}

function localeConstName(lang: UiLang): string {
  return lang.toUpperCase().replace(/-/g, "_");
}

async function writePdfViewerLocales(): Promise<void> {
  const locales = Object.fromEntries(
    UI_LANGS.map((lang) => [lang, pdfViewerLocale(lang)]),
  );
  const pdfjs = Object.fromEntries(
    UI_LANGS.map((lang) => [lang, pdfJsLocale(lang, locales[lang] ?? {})]),
  );

  const source = [
    "// Generated by scripts/generate-i18n.ts. Do not edit directly.",
    `export const PDF_VIEWER_SUPPORTED_UI_LANGS = ${json(UI_LANGS)};`,
    "",
    `export const PDF_VIEWER_LOCALES = ${json(locales)};`,
    "",
    `export const PDF_VIEWER_PDFJS_L10N = ${json(pdfjs)};`,
    "",
  ].join("\n");

  await writeFile(PDF_VIEWER_LOCALE_FILE, source, "utf8");
}

function pdfViewerLocale(lang: UiLang): RuntimeDict {
  const entries = Object.keys(EN_MESSAGES)
    .filter((key) => key.startsWith(PDF_VIEWER_PREFIX))
    .filter((key) => !key.startsWith(PDFJS_PREFIX))
    .map((key) => [
      key.slice(PDF_VIEWER_PREFIX.length),
      message(lang, key as MessageKey),
    ]);
  return Object.fromEntries(entries);
}

function pdfJsLocale(lang: UiLang, locale: RuntimeDict): Record<string, unknown> {
  return {
    "pdfjs-editor-free-text-button": { title: locale.text },
    "pdfjs-editor-free-text-button-label": locale.text,
    "pdfjs-editor-highlight-button": { title: locale.highlight },
    "pdfjs-editor-highlight-button-label": locale.highlight,
    "pdfjs-editor-ink-button": { title: locale.draw },
    "pdfjs-editor-ink-button-label": locale.draw,
    "pdfjs-editor-stamp-button": { title: locale.addImage },
    "pdfjs-editor-stamp-button-label": locale.addImage,
    "pdfjs-editor-highlight-editor": {
      "aria-label": message(lang, PDFJS_MESSAGE_KEYS.highlightEditor),
    },
    "pdfjs-editor-ink-editor": {
      "aria-label": message(lang, PDFJS_MESSAGE_KEYS.inkEditor),
    },
    "pdfjs-editor-stamp-editor": {
      "aria-label": message(lang, PDFJS_MESSAGE_KEYS.stampEditor),
    },
    "pdfjs-free-text2": {
      "aria-label": message(lang, PDFJS_MESSAGE_KEYS.textEditor),
      "default-content": message(lang, PDFJS_MESSAGE_KEYS.freeTextDefaultContent),
    },
    "pdfjs-page-landmark": {
      "aria-label": message(lang, PDFJS_MESSAGE_KEYS.pageLandmark),
    },
    "pdfjs-page-scale-auto": locale.scaleAuto,
    "pdfjs-page-scale-fit": locale.scalePageFit,
    "pdfjs-page-scale-width": locale.scalePageWidth,
  };
}

function message(lang: UiLang, key: MessageKey): string {
  return I18N_CATALOG[lang][key] ?? EN_MESSAGES[key];
}

function json(value: unknown): string {
  return JSON.stringify(value, null, 2);
}

await main();
